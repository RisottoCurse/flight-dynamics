clear;
clc;
close all;

%% Constants

mu = 3.986004418e14;  % Earth GM [m^3/s^2]
Re = 6378137;         % Earth radius [m]

burnTime = 1800;      % Manoeuvre epoch [s]

%% Load C++ propagation results

nominal = readtable("notebook/manoeuvre/nominal.csv");
manoeuvre = readtable("notebook/manoeuvre/manoeuvre.csv");

% Time
tNominal = nominal.time;
tManoeuvre = manoeuvre.time;

% ECI position [m]
rNominal = [nominal.x, nominal.y, nominal.z];
rManoeuvre = [manoeuvre.x, manoeuvre.y, manoeuvre.z];

% ECI velocity [m/s]
vNominal = [nominal.u, nominal.v, nominal.w];
vManoeuvre = [manoeuvre.u, manoeuvre.v, manoeuvre.w];

%% Calculate orbital parameters

% Position magnitude
rN = vecnorm(rNominal, 2, 2);
rM = vecnorm(rManoeuvre, 2, 2);

% Velocity magnitude
vN = vecnorm(vNominal, 2, 2);
vM = vecnorm(vManoeuvre, 2, 2);

% Specific orbital energy
energyNominal = 0.5 * vN.^2 - mu ./ rN;
energyManoeuvre = 0.5 * vM.^2 - mu ./ rM;

% Semi-major axis
aNominal = -mu ./ (2 * energyNominal);
aManoeuvre = -mu ./ (2 * energyManoeuvre);

% Specific angular momentum
hNominal = cross(rNominal, vNominal, 2);
hManoeuvre = cross(rManoeuvre, vManoeuvre, 2);

% Eccentricity vectors
eVectorNominal = ...
    cross(vNominal, hNominal, 2) ./ mu ...
    - rNominal ./ rN;

eVectorManoeuvre = ...
    cross(vManoeuvre, hManoeuvre, 2) ./ mu ...
    - rManoeuvre ./ rM;

% Eccentricity magnitude
eNominal = vecnorm(eVectorNominal, 2, 2);
eManoeuvre = vecnorm(eVectorManoeuvre, 2, 2);

%% Plot styling

backgroundColour = [0.06 0.07 0.10];
foregroundColour = [0.92 0.92 0.92];

nominalColour = [0.20 0.65 1.00];
manoeuvreColour = [1.00 0.40 0.30];
burnColour = [1.00 0.85 0.20];

%% Figure 1: 3D ECI orbital trajectories

figure('Color', backgroundColour, ...
       'Name', 'Impulsive Manoeuvre - ECI Trajectories');

hold on;

% Earth sphere
[X, Y, Z] = sphere(60);

surf(Re * X / 1000, ...
     Re * Y / 1000, ...
     Re * Z / 1000, ...
     'FaceColor', [0.10 0.30 0.60], ...
     'EdgeColor', 'none', ...
     'FaceAlpha', 0.65, ...
     'HandleVisibility', 'off');

%% ECI Coordinate Axes

% Length of ECI coordinate axes [km]
axisLength = 9000;

% ECI X-axis (red)
quiver3(0, 0, 0, ...
        axisLength, 0, 0, ...
        0, ...
        'Color', [1.0 0.2 0.2], ...
        'LineWidth', 2.5, ...
        'MaxHeadSize', 0.3, ...
        'DisplayName', 'ECI X');

% ECI Y-axis (green)
quiver3(0, 0, 0, ...
        0, axisLength, 0, ...
        0, ...
        'Color', [0.2 1.0 0.2], ...
        'LineWidth', 2.5, ...
        'MaxHeadSize', 0.3, ...
        'DisplayName', 'ECI Y');

% ECI Z-axis (blue)
quiver3(0, 0, 0, ...
        0, 0, axisLength, ...
        0, ...
        'Color', [0.2 0.6 1.0], ...
        'LineWidth', 2.5, ...
        'MaxHeadSize', 0.3, ...
        'DisplayName', 'ECI Z');

% Nominal trajectory
plot3( ...
    rNominal(:,1)/1000, ...
    rNominal(:,2)/1000, ...
    rNominal(:,3)/1000, ...
    'Color', nominalColour, ...
    'LineWidth', 1.8, ...
    'DisplayName', 'Nominal Orbit');

% Manoeuvred trajectory
plot3( ...
    rManoeuvre(:,1)/1000, ...
    rManoeuvre(:,2)/1000, ...
    rManoeuvre(:,3)/1000, ...
    'Color', manoeuvreColour, ...
    'LineWidth', 2.0, ...
    'DisplayName', 'Manoeuvred Orbit');

%% Initial Starting Position

rInitial = rNominal(1,:);
scatter3( ...
    rInitial(1)/1000, ...
    rInitial(2)/1000, ...
    rInitial(3)/1000, ...
    120, ...
    [0.20 1.00 0.40], ...
    'filled', ...
    'MarkerEdgeColor', 'white', ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Initial Position');

% Burn location
burnIndex = find(tManoeuvre >= burnTime, 1, 'first');

rBurn = rManoeuvre(burnIndex,:);

scatter3( ...
    rBurn(1)/1000, ...
    rBurn(2)/1000, ...
    rBurn(3)/1000, ...
    90, ...
    burnColour, ...
    'filled', ...
    'DisplayName', 'Manoeuvre Location');

% Delta-v direction
vBefore = vManoeuvre(burnIndex,:);
vAfter = vManoeuvre(burnIndex+1,:);

deltaV = vAfter - vBefore;
deltaVUnit = deltaV / norm(deltaV);

arrowLength = 1000;  % Arrow length [km]

quiver3( ...
    rBurn(1)/1000, ...
    rBurn(2)/1000, ...
    rBurn(3)/1000, ...
    arrowLength * deltaVUnit(1), ...
    arrowLength * deltaVUnit(2), ...
    arrowLength * deltaVUnit(3), ...
    0, ...
    'Color', burnColour, ...
    'LineWidth', 2.0, ...
    'MaxHeadSize', 0.8, ...
    'DisplayName', '\Delta v Direction');

% Axis styling
axis equal;
grid on;
view(35, 25);

xlabel('X ECI [km]');
ylabel('Y ECI [km]');
zlabel('Z ECI [km]');

title('Impulsive Manoeuvre: ECI Trajectories');

ax = gca;
ax.Color = backgroundColour;
ax.XColor = foregroundColour;
ax.YColor = foregroundColour;
ax.ZColor = foregroundColour;
ax.GridColor = [0.5 0.5 0.5];

legend('Location', 'best', 'TextColor', foregroundColour);

lighting gouraud;
camlight headlight;

%% Figure 2: Semi-major axis

figure('Color', backgroundColour, ...
       'Name', 'Semi-major Axis');

hold on;

plot(tNominal/3600, aNominal/1000, ...
    'Color', nominalColour, ...
    'LineWidth', 1.8, ...
    'DisplayName', 'Nominal');

plot(tManoeuvre/3600, aManoeuvre/1000, ...
    'Color', manoeuvreColour, ...
    'LineWidth', 2.0, ...
    'DisplayName', 'Manoeuvred');

xline(burnTime/3600, '--', ...
    'Color', burnColour, ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Burn');

xlabel('Time [hours]');
ylabel('Semi-major Axis [km]');
title('Semi-major Axis vs Time');

grid on;
legend('Location', 'best');

ax = gca;
ax.Color = backgroundColour;
ax.XColor = foregroundColour;
ax.YColor = foregroundColour;
ax.GridColor = [0.5 0.5 0.5];

%% Figure 3: Eccentricity

figure('Color', backgroundColour, ...
       'Name', 'Eccentricity');

hold on;

plot(tNominal/3600, eNominal, ...
    'Color', nominalColour, ...
    'LineWidth', 1.8, ...
    'DisplayName', 'Nominal');

plot(tManoeuvre/3600, eManoeuvre, ...
    'Color', manoeuvreColour, ...
    'LineWidth', 2.0, ...
    'DisplayName', 'Manoeuvred');

xline(burnTime/3600, '--', ...
    'Color', burnColour, ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Burn');

xlabel('Time [hours]');
ylabel('Eccentricity');
title('Eccentricity vs Time');

grid on;
legend('Location', 'best');

ax = gca;
ax.Color = backgroundColour;
ax.XColor = foregroundColour;
ax.YColor = foregroundColour;
ax.GridColor = [0.5 0.5 0.5];

%% Figure 4: Specific orbital energy

figure('Color', backgroundColour, ...
       'Name', 'Specific Orbital Energy');

hold on;

plot(tNominal/3600, energyNominal/1e6, ...
    'Color', nominalColour, ...
    'LineWidth', 1.8, ...
    'DisplayName', 'Nominal');

plot(tManoeuvre/3600, energyManoeuvre/1e6, ...
    'Color', manoeuvreColour, ...
    'LineWidth', 2.0, ...
    'DisplayName', 'Manoeuvred');

xline(burnTime/3600, '--', ...
    'Color', burnColour, ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Burn');

xlabel('Time [hours]');
ylabel('Specific Orbital Energy [MJ/kg]');
title('Specific Orbital Energy vs Time');

grid on;
legend('Location', 'best');

ax = gca;
ax.Color = backgroundColour;
ax.XColor = foregroundColour;
ax.YColor = foregroundColour;
ax.GridColor = [0.5 0.5 0.5];

%% Print results

fprintf('\n=== Impulsive Manoeuvre Results ===\n');

fprintf('Initial semi-major axis: %.3f km\n', ...
    aManoeuvre(1)/1000);

fprintf('Final semi-major axis: %.3f km\n', ...
    aManoeuvre(end)/1000);

fprintf('Initial eccentricity: %.6f\n', ...
    eManoeuvre(1));

fprintf('Final eccentricity: %.6f\n', ...
    eManoeuvre(end));

fprintf('Energy change: %.6f MJ/kg\n', ...
    (energyManoeuvre(burnIndex+1) ...
    - energyManoeuvre(burnIndex))/1e6);

fprintf('Delta-V magnitude: %.3f m/s\n', ...
    norm(deltaV));


%% Validate impulsive manoeuvre energy change

% Velocity immediately before manoeuvre
vBefore = vManoeuvre(burnIndex,:);

% Velocity immediately after manoeuvre
vAfter = vManoeuvre(burnIndex+1,:);

% Applied velocity change
deltaV = vAfter - vBefore;

% Theoretical energy change
deltaEnergyAnalytical = ...
    dot(vBefore, deltaV) ...
    + 0.5 * dot(deltaV, deltaV);

% Numerical energy change
deltaEnergyNumerical = ...
    energyManoeuvre(burnIndex+1) ...
    - energyManoeuvre(burnIndex);

% Relative error
relativeError = ...
    abs(deltaEnergyNumerical - deltaEnergyAnalytical) ...
    / abs(deltaEnergyAnalytical);

fprintf('\n=== Energy Validation ===\n');

fprintf('Analytical energy change: %.12f J/kg\n', ...
    deltaEnergyAnalytical);

fprintf('Numerical energy change: %.12f J/kg\n', ...
    deltaEnergyNumerical);

fprintf('Relative error: %.3e\n', ...
    relativeError);